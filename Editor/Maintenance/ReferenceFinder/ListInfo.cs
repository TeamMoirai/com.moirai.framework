namespace Moirai.Atropos.ReferenceFinder
{
    /// <summary>
    /// 引用列表的统计信息条目（数量、名称与类型）。
    /// </summary>
    internal sealed class ListInfo
    {
        /// <summary>
        /// 列表数量。
        /// </summary>
        public int Count;

        /// <summary>
        /// 列表名称。
        /// </summary>
        public string Name;

        /// <summary>
        /// 列表类型。
        /// </summary>
        public string Type;
    }
}