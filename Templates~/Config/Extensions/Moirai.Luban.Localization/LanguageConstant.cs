using System.Text;

namespace Moirai.LubanLocalization;

/// <summary>
/// 语言常量文件（L10nLanguages.Codes）的生成与 Luban 生成码的头部修正。
/// 内容与 gen.sh 的 generate_language_constant / strip_generated_header_blank_line 逐字节一致，
/// 保证插件路线与旧路线的产物可互相替换、CHECK 可互验。
/// </summary>
internal static class LanguageConstant
{
    private static readonly UTF8Encoding Utf8 = new(encoderShouldEmitUTF8Identifier: false);

    internal static byte[] Build(string[] languages, string namespaceName)
    {
        var output = new StringBuilder();
        // 与 gen.sh 的 printf '\xef\xbb\xbf' 一致：BOM 打头，行尾 LF，结尾一个换行
        output.Append('\ufeff');
        AppendLine(output, "//------------------------------------------------------------------------------");
        AppendLine(output, "// <auto-generated>");
        AppendLine(output, "//     This code was generated by a tool.");
        AppendLine(output, "//     Changes to this file may cause incorrect behavior and will be lost if");
        AppendLine(output, "//     the code is regenerated.");
        AppendLine(output, "// </auto-generated>");
        AppendLine(output, "//------------------------------------------------------------------------------");
        AppendLine(output, "");
        AppendLine(output, $"namespace {namespaceName}");
        AppendLine(output, "{");
        AppendLine(output, "    /// <summary>");
        AppendLine(output, "    /// 本次转表导出了哪几种语言，顺序即框架内的列序（回退链按此下标取列）。");
        AppendLine(output, "    /// 每种语言的数据在配置表根目录下的同名子目录里；用哪一种语言由 LocalizationService 决定。");
        AppendLine(output, "    /// </summary>");
        AppendLine(output, "    public static class L10nLanguages");
        AppendLine(output, "    {");
        AppendLine(output, "        public static readonly string[] Codes =");
        AppendLine(output, "        {");
        for (int i = 0; i < languages.Length; i++)
        {
            string comma = i < languages.Length - 1 ? "," : string.Empty;
            AppendLine(output, $"            \"{languages[i]}\"{comma}");
        }
        AppendLine(output, "        };");
        AppendLine(output, "    }");
        AppendLine(output, "}");
        return Utf8.GetBytes(output.ToString());
    }

    /// <summary>
    /// Luban 的 file header 模板自带一个前导空行，gen.sh 旧路线用 tail -n +2 统一剥掉；
    /// 这里对暂存区里的 Luban 生成 .cs 做同样处理（语言常量文件自己生成，排除在外）。
    /// </summary>
    internal static void StripGeneratedHeaderBlankLine(string directory, string excludeFile)
    {
        string excludeFull = Path.GetFullPath(excludeFile);
        foreach (string file in Directory.GetFiles(directory, "*.cs", SearchOption.AllDirectories))
        {
            if (string.Equals(Path.GetFullPath(file), excludeFull, PathComparison)) continue;
            byte[] bytes = File.ReadAllBytes(file);
            int firstNewline = Array.IndexOf(bytes, (byte)'\n');
            if (firstNewline < 0) continue;
            // 首行（到第一个 \n 之前）去掉 \r 后为空才算空行；BOM 等其他字节算非空，与 bash 口径一致
            bool blank = true;
            for (int i = 0; i < firstNewline; i++)
            {
                if (bytes[i] != (byte)'\r')
                {
                    blank = false;
                    break;
                }
            }
            if (blank) File.WriteAllBytes(file, bytes[(firstNewline + 1)..]);
        }
    }

    private static void AppendLine(StringBuilder output, string line) => output.Append(line).Append('\n');

    internal static readonly StringComparison PathComparison =
        OperatingSystem.IsWindows() ? StringComparison.OrdinalIgnoreCase : StringComparison.Ordinal;
}
