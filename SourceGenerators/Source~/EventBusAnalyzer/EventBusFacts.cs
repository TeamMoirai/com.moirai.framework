using System;
using System.Collections.Concurrent;
using System.Linq;
using System.Text.RegularExpressions;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Moirai.EventBus.Roslyn;

/// <summary>
/// EventBus 体系公共事实：类型/方法识别、OnXxxEvent 命名约定、生成代码文件判定。
/// </summary>
internal static class EventBusFacts
{
    /// <summary>EventBus 全限定名（内核管线静态类）。</summary>
    private const string EventBusMetadataName = "Moirai.Atropos.EventBus";

    /// <summary>IGameEvent 全限定名（总线事件标记接口）。</summary>
    public const string GameEventInterfaceMetadataName = "Moirai.Atropos.IGameEvent";

    /// <summary>OnXxxEvent 命名约定：On 前缀 + Event 后缀（OnFooEvent → FooEvent）。</summary>
    private static readonly Regex OnEventCallbackPattern = new(
        @"^On(?<body>[A-Za-z_][A-Za-z0-9_]*)Event$",
        RegexOptions.Compiled | RegexOptions.CultureInvariant);

    /// <summary>是否为 EventBus.Subscribe / EventBus.Unsubscribe 方法符号。</summary>
    public static bool IsSubscribeOrUnsubscribe(IMethodSymbol? method)
    {
        if (method is null) return false;

        var definition = method.OriginalDefinition;
        if (definition.Name is not ("Subscribe" or "Unsubscribe")) return false;

        var containingType = definition.ContainingType;
        return containingType is { IsStatic: true, Arity: 0 }
            && string.Equals(containingType.ToDisplayString(), EventBusMetadataName, StringComparison.Ordinal);
    }

    /// <summary>方法名是否符合 OnXxxEvent 命名约定；命中时返回事件类型名（FooEvent）。</summary>
    public static bool IsOnEventCallbackName(string methodName, out string eventName)
    {
        var match = OnEventCallbackPattern.Match(methodName);
        if (!match.Success)
        {
            eventName = string.Empty;
            return false;
        }

        eventName = match.Groups["body"].Value + "Event";
        return true;
    }

    /// <summary>类型是否为 struct 且实现 IGameEvent（总线事件契约）。</summary>
    public static bool IsBusEventStruct(ITypeSymbol? type)
    {
        if (type is not INamedTypeSymbol named || named.TypeKind != TypeKind.Struct) return false;
        if (named.OriginalDefinition.Arity != 0) return false;
        return named.AllInterfaces.Any(i => string.Equals(
            i.OriginalDefinition.ToDisplayString(),
            GameEventInterfaceMetadataName,
            StringComparison.Ordinal));
    }

    /// <summary>解析编译内按名声明的总线事件类型（无参回调 OnFooEvent → FooEvent 符号）。</summary>
    public static INamedTypeSymbol? ResolveBusEventByName(Compilation compilation, string eventName)
    {
        foreach (var symbol in compilation.GetSymbolsWithName(eventName, SymbolFilter.Type))
        {
            if (symbol is INamedTypeSymbol t && IsBusEventStruct(t))
                return t;
        }

        return null;
    }

    // <auto-generated> 文件头判定（带按树缓存——避免逐节点重复扫描全文本）
    private static readonly ConcurrentDictionary<SyntaxTree, bool> GeneratedTreeCache = new();

    public static bool IsGeneratedCode(SyntaxTree tree)
    {
        if (tree is null) return false;
        return GeneratedTreeCache.GetOrAdd(tree, static t =>
        {
            var root = t.GetCompilationUnitRoot();
            var header = root.EndOfFileToken.LeadingTrivia.ToString();
            var firstToken = root.ChildTokens().FirstOrDefault();
            header += firstToken.LeadingTrivia.ToString();
            return header.IndexOf("<auto-generated", StringComparison.OrdinalIgnoreCase) >= 0
                || header.IndexOf("auto-generated", StringComparison.OrdinalIgnoreCase) >= 0;
        });
    }
}
